const GLYPHS = {};
for (const [k, rows] of Object.entries(RAW)) {
  GLYPHS[k] = { w: rows[0].length, rows };
}

export function textWidth(str) {
  let w = 0;
  for (const ch of str.toUpperCase()) w += ((GLYPHS[ch] || GLYPHS[' ']).w) + 1;
  return Math.max(0, w - 1);
}

// Возвращает функцию (u, v) -> bool для надписи, вписанной в прямоугольник [u0..u0+w] x [v0..v0+5]
// u растёт вправо, v — вверх (как на стенах).
export function textMask(str, u0, v0) {
  str = str.toUpperCase();
  const cols = [];
  for (const ch of str) {
    const g = GLYPHS[ch] || GLYPHS[' '];
    for (let x = 0; x < g.w; x++) cols.push(g.rows.map((r) => r[x] === '#'));
    cols.push([false, false, false, false, false]);
  }
  cols.pop();
  return (u, v) => {
    const x = Math.floor(u - u0), y = 4 - Math.floor(v - v0);
    if (x < 0 || x >= cols.length || y < 0 || y > 4) return false;
    return cols[x][y];
  };
}

// Рисует текст прямо в 2D-контекст (для UI-иконок)
export function drawText(ctx, str, x, y, color) {
  ctx.fillStyle = color;
  for (const ch of str.toUpperCase()) {
    const g = GLYPHS[ch] || GLYPHS[' '];
    for (let r = 0; r < 5; r++) for (let c = 0; c < g.w; c++) if (g.rows[r][c] === '#') ctx.fillRect(x + c, y + r, 1, 1);
    x += g.w + 1;
  }
}
